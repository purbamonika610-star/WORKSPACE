export function makeT(lang) {
  const i = lang === 'en' ? 0 : 1;
  return (key, vars) => {
    let s = dict[key] ? dict[key][i] : key;
    if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
    return s;
  };
}

// Pick the right language from a {en,id} object or return a plain string.
export function tx(v, lang) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  return v[lang] || v.en || v.id || '';
}
